def encounter_multiplier(count: int, party_size: int) -> float:
    """Множитель опыта за число монстров (с. 165) с поправкой на размер отряда (с. 166):
    меньше трёх героев — следующий множитель вверх, шесть и больше — вниз."""
    if count <= 1:
        idx = 1
    elif count == 2:
        idx = 2
    elif count <= 6:
        idx = 3
    elif count <= 10:
        idx = 4
    elif count <= 14:
        idx = 5
    else:
        idx = 6
    if party_size < 3:
        idx += 1
    elif party_size >= 6:
        idx -= 1
    idx = max(0, min(len(_MULTIPLIER_STEPS) - 1, idx))
    return _MULTIPLIER_STEPS[idx]


